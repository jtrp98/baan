function tomlBasicString(text) {
  return JSON.stringify(String(text ?? ""));
}

export function compileCodexAgentToml(id, teamDir = TEAM_DIR, cfg = null) {
  const a = TEAM_AGENTS[id];
  const resolvedCfg = cfg ?? loadRolesConfig(teamDir);
  const rc = roleProviderConfig(resolvedCfg, id, "codex");
  const style = loadStyleOverlay("codex", teamDir);
  const rolePath = path.join(teamDir, "roles", `${id}.md`);
  const convPath = path.join(teamDir, "CONVENTIONS.md");
  const learnPath = path.join(teamDir, "LEARNING.md");

  const instructions = [
    `# Role: ${id} (${a.what})`,
    `Read and follow the core role contract: ${rolePath}`,
    `Conventions: ${convPath} | Learning Contract: ${learnPath}`,
    "",
    `## Role Tier Ladder (default: ${rc.defaultTier})`,
    ...rc.ladder.map((l) => `- ${l}`),
    "",
    "## 3-Step Workflow",
    "1. Explore context in parallel using collaboration.spawn_agent + collaboration.wait_agent.",
    "2. Run /plan first and align with the user before editing or writing deliverables.",
    "3. Delegate approved long-form documentation updates to a subagent (1 writer per repository).",
    "Answer in Thai; keep code and identifiers in English.",
    "",
    style,
  ].join("\n").trim();

  const lines = [
    TOML_STUB_MARKER,
    `name = ${tomlBasicString(id)}`,
    `description = ${tomlBasicString(`${a.what} — ต้องระบุ project และ module`)}`,
  ];
  if (rc.model) lines.push(`model = ${tomlBasicString(rc.model)}`);
  if (rc.effort) lines.push(`model_reasoning_effort = ${tomlBasicString(rc.effort)}`);
  lines.push(`developer_instructions = ${tomlBasicString(instructions)}`);
  lines.push("");
  return lines.join("\n");
}
