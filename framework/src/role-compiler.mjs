function loadStyleOverlay(provider, teamDir) {
  const file = path.join(teamDir, "roles", "providers", provider, "_style.md");
  return existsSync(file) ? readFileSync(file, "utf8").trim() : "";
}

function loadRolesConfig(teamDir) {
  const file = path.join(teamDir, "agents.json");
  if (!existsSync(file)) return loadAgentsConfig();
  return JSON.parse(readFileSync(file, "utf8"));
}

function roleProviderConfig(cfg, id, provider) {
  const def = cfg?.roles?.[id];
  if (!def?.tiers) return { defaultTier: "t2", model: "", effort: "", ladder: [] };
  const defaultTier = def.defaultTier || sortedRoleTiers(def)[0] || "t2";
  const td = def.tiers[defaultTier] ?? {};
  const entry = td[provider] ?? {};
  const ladder = sortedRoleTiers(def).map((t) => {
    const c = def.tiers[t]?.[provider];
    return `${t}: ${c ? `${c.model}/${c.effort}` : "n/a"} (${def.tiers[t]?.label ?? ""})`;
  });
  return {
    defaultTier,
    model: entry.model ?? "",
    effort: entry.effort ?? "",
    ladder,
  };
}

