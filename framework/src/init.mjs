import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROLE_SESSION_RULE } from "./role-guard.mjs";

const STUB_MARKER = "<!-- generated by: baan --init -->";

function stubContent(charterPath, learningPath) {
  return `${STUB_MARKER}
# 🏗️ นายช่าง — BAAN

> **ข้อยกเว้น — อ่านก่อน:** ${ROLE_SESSION_RULE}

ถ้าไม่เข้าข้อยกเว้น: คุณคือ นายช่าง — อ่านและทำตาม ${charterPath} และ ${learningPath}
ใช้ baan run / status / inbox / decide / report / sync
เมื่อผู้ใช้สั่ง "ซิงค์", "อัปเดต", "pull ล่าสุด", หรือ "ส่งงาน" ให้เรียกใช้ baan sync
วางแผนก่อนทำเสมอ (/plan first) ทุกครั้งที่มีการตัดสินใจทางเทคนิคสำคัญให้ผ่าน Learning Protocol และ Decision Quality Gate
ยืนยัน acceptance/scope/commands ก่อน dispatch และยืนยันใหม่เมื่อ basis เปลี่ยน; human gates ยืนยันแยก ห้ามอนุมัติแทนผู้ใช้
ทีมสร้าง (spec, arch, pm, build, check) และทีมออกแบบ (survey, ui, review) ใช้ผ่าน .claude/agents/ โดยใช้ 3-step workflow และ Subagents เสมอ
config: ./baan.config.json
`;
}

const toPosix = (p) => p.split(path.sep).join("/");

function cloneInto(url, dest, log) {
  if (existsSync(dest)) { log(`มี ${dest} อยู่แล้ว (ไม่ clone ทับ)`); return "kept"; }
  const r = spawnSync("git", ["clone", url, dest], { encoding: "utf8", windowsHide: true });
  if (r.status !== 0) throw new Error(`git clone ไม่สำเร็จ: ${(r.error?.message || r.stderr || "unknown Git error").trim().slice(-3000)}`);
  log(`clone ${url} → ${dest}`);
  return "cloned";
}

function generatedConfig(teamDir, targetDir, knowledgeDir, memoryDir, knowledgeName) {
  const example = JSON.parse(readFileSync(path.join(teamDir, "baan.example.json"), "utf8"));
  return {
    knowledge_roots: [{
      name: knowledgeName,
      path: toPosix(knowledgeDir),
      layout: "project",
      ...(memoryDir ? { memory_root: toPosix(memoryDir) } : {}),
      targets: [],
    }],
    defaults: example.defaults,
  };
}

