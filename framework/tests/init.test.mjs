test("init: ต้องสร้างโฟลเดอร์ target/ เป็นมาตรฐาน และลบเฉพาะ baan.cmd ที่เป็น wrapper เรียก BAAN", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-clean-"));
  try {
    writeFileSync(path.join(dir, "baan.cmd"), "@echo off\nnode C:\\src\\AICode\\baan\\framework\\bin\\baan.mjs %*\n", "utf8");
    const logs = [];
    performInit(dir, TEAM_DIR, (m) => logs.push(m));
    assert.equal(existsSync(path.join(dir, "target")), true, "ต้องสร้างโฟลเดอร์ target/ ให้เสมอ");
    assert.equal(existsSync(path.join(dir, "baan.cmd")), false, "wrapper เก่าของ BAAN ต้องถูกลบ");
    assert.ok(logs.some((l) => l.includes("ลบ baan.cmd เดิม")));

    writeFileSync(path.join(dir, "baan.cmd"), "@echo off\nnode my-own-tool.js\n", "utf8");
    performInit(dir, TEAM_DIR, () => {});
    assert.equal(readFileSync(path.join(dir, "baan.cmd"), "utf8"), "@echo off\nnode my-own-tool.js\n", "baan.cmd ของผู้ใช้ต้องไม่ถูกลบ");
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("init ซ้ำ: เก็บข้อความที่ผู้ใช้/Claude memory เขียนต่อท้าย stub ไว้ ทั้งแบบมี end marker และ stub รุ่นเก่า", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-tail-"));
  try {
    performInit(dir, TEAM_DIR, () => {});
    const file = path.join(dir, "CLAUDE.md");
    const fresh = readFileSync(file, "utf8");
    assert.match(fresh, /baan:end/);

    writeFileSync(file, `${fresh}- จำไว้: ใช้ pnpm ไม่ใช่ npm\n`, "utf8");
    performInit(dir, TEAM_DIR, () => {});
    assert.equal(readFileSync(file, "utf8"), `${fresh}- จำไว้: ใช้ pnpm ไม่ใช่ npm\n`);

    // A 0.36-era stub had no end marker; Claude's "#" memory appended after its last line.
    const legacy = fresh.slice(0, fresh.indexOf("<!-- baan:end"));
    writeFileSync(file, `${legacy}\n- memory เก่า\n`, "utf8");
    performInit(dir, TEAM_DIR, () => {});
    assert.equal(readFileSync(file, "utf8"), `${fresh}- memory เก่า\n`);
    assert.equal(existsSync(`${file}.baan-backup`), false);

    // Unknown older layout: keep the whole old file as a backup instead of guessing.
    writeFileSync(file, "<!-- generated by: baan --init -->\n# old layout\n- note\n", "utf8");
    const logs = [];
    performInit(dir, TEAM_DIR, (m) => logs.push(m));
    assert.equal(readFileSync(`${file}.baan-backup`, "utf8"), "<!-- generated by: baan --init -->\n# old layout\n- note\n");
    assert.equal(readFileSync(file, "utf8"), fresh);
    assert.ok(logs.some((l) => l.includes(".baan-backup")));
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("defect records always point at the knowledge project, never a bare shared/ at the workspace root", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-defects-"));
  try {
    performInit(dir, TEAM_DIR, () => {});
    const sources = {
      "CLAUDE.md (generated)": readFileSync(path.join(dir, "CLAUDE.md"), "utf8"),
      ...Object.fromEntries(["skills/bug-fix/SKILL.md", "README.md", "BAAN.md", "CONVENTIONS.md", "roles/build.md"].map((f) => [f, readFileSync(path.join(TEAM_DIR, f), "utf8")])),
    };
    for (const [name, text] of Object.entries(sources)) {
      for (const m of text.matchAll(/shared\/defects/g)) {
        assert.match(text.slice(Math.max(0, m.index - 10), m.index), /<project>\/$/, `${name}: "shared/defects" must be written as <project>/shared/defects`);
      }
    }
    assert.match(sources["CLAUDE.md (generated)"], /<project>\/shared\/defects\//);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("init ติดตั้ง telemetry hooks (agy, claude, codex) ที่ราก workspace โดยไม่แตะ target/ และ merge อย่างปลอดภัย", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-hooks-"));
  try {
    mkdirSync(path.join(dir, ".agents"), { recursive: true });
    mkdirSync(path.join(dir, ".claude"), { recursive: true });
    mkdirSync(path.join(dir, ".codex"), { recursive: true });
    writeFileSync(path.join(dir, ".agents", "hooks.json"), JSON.stringify({ "user-hook": { Stop: [{ command: "echo ok" }] } }), "utf8");
    writeFileSync(path.join(dir, ".claude", "settings.json"), JSON.stringify({ model: "sonnet", hooks: { Stop: [{ hooks: [{ type: "command", command: "echo user" }] }] } }), "utf8");
    writeFileSync(path.join(dir, ".codex", "hooks.json"), "{broken-json", "utf8");

    const logs = [];
    const res = performInit(dir, TEAM_DIR, (m) => logs.push(m));
    assert.ok(existsSync(path.join(dir, ".agents", "hooks", "baan-live-telemetry.mjs")));
    assert.equal(existsSync(path.join(dir, "target", ".agents")), false, "ห้ามติดตั้งลงใน target/");
    assert.match(readFileSync(path.join(dir, "CLAUDE.md"), "utf8"), /ห้ามติดตั้งลงใน `target\/`/);

    const agyHooks = JSON.parse(readFileSync(path.join(dir, ".agents", "hooks.json"), "utf8"));
    assert.ok(agyHooks["user-hook"], "ต้องรักษา user hook เดิม");
    assert.ok(agyHooks["baan-live-telemetry"].PreToolUse[0].matcher === "invoke_subagent");

    const claudeSettings = JSON.parse(readFileSync(path.join(dir, ".claude", "settings.json"), "utf8"));
    assert.equal(claudeSettings.model, "sonnet");
    assert.equal(claudeSettings.hooks.Stop.length, 2, "ต้องเก็บ user Stop hook เดิมไว้ร่วมกับ BAAN hook");

    assert.equal(readFileSync(path.join(dir, ".codex", "hooks.json"), "utf8"), "{broken-json", "JSON เสียรูปต้องไม่ถูกเขียนทับ");
    assert.ok(res.skipped.includes(path.join(dir, ".codex", "hooks.json")));

    // Idempotent second run: no duplicate entries in Claude settings.
    performInit(dir, TEAM_DIR, () => {});
    const claudeAgain = JSON.parse(readFileSync(path.join(dir, ".claude", "settings.json"), "utf8"));
    assert.equal(claudeAgain.hooks.Stop.length, 2);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
