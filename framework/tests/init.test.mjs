import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { performInit } from "../src/init.mjs";

const TEAM_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

test("init ครั้งแรก: สร้าง baan.config.json จากตัวอย่าง + CLAUDE.md + AGENTS.md + GEMINI.md และ native agents ครบ 3 ค่าย", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-"));
  try {
    const logs = [];
    const res = performInit(dir, TEAM_DIR, (m) => logs.push(m));
    assert.equal(res.config, "written");
    assert.deepEqual(res.stubs.sort(), ["AGENTS.md", "CLAUDE.md", "GEMINI.md"]);
    assert.equal(res.skipped.length, 0);
    const cfgFile = path.join(dir, "baan.config.json");
    assert.equal(readFileSync(cfgFile, "utf8"), readFileSync(path.join(TEAM_DIR, "baan.example.json"), "utf8"));
    assert.equal(existsSync(path.join(dir, "baan")), false, "ไม่ต้องมีโฟลเดอร์ baan แล้ว");
    for (const name of ["CLAUDE.md", "AGENTS.md", "GEMINI.md"]) {
      const content = readFileSync(path.join(dir, name), "utf8");
      assert.match(content, /generated by: baan --init/);
      assert.ok(content.includes(path.join(TEAM_DIR, "BAAN.md")), `${name} ต้องชี้ path ของ charter`);
      assert.ok(content.includes(path.join(TEAM_DIR, "LEARNING.md")), `${name} ต้องชี้ path ของ learning contract`);
      assert.ok(content.includes("baan.config.json"), `${name} ต้องบอกตำแหน่ง config`);
      assert.ok(content.includes("bug-fix"), `${name} ต้องมีคำสั่ง bug-fix`);
      assert.ok(content.includes("เริ่มงานด้วย BAAN เสมอ"), `${name} ต้องมีคำสั่งเริ่มงานด้วย BAAN`);
    }
    // Provider-native workspace agents installed at workspace root only
    const claudeArch = readFileSync(path.join(dir, ".claude", "agents", "arch.md"), "utf8");
    assert.match(claudeArch, /^model: opus$/m);
    assert.match(claudeArch, /^effort: high$/m);
    assert.match(claudeArch, /<role_contract>/);

    const agyArch = readFileSync(path.join(dir, ".agents", "agents", "arch.md"), "utf8");
    assert.match(agyArch, /^model: gemini-4-neon$/m);
    assert.match(agyArch, /Explore -> Plan -> Execute/);

    const agyCheck = readFileSync(path.join(dir, ".agents", "agents", "check.md"), "utf8");
    assert.ok(!agyCheck.includes("write_file"), "check agent บน agy ต้องเป็น read-only");
    assert.ok(!agyCheck.includes("edit_file"), "check agent บน agy ต้องเป็น read-only");

    const codexBuild = readFileSync(path.join(dir, ".codex", "agents", "build.toml"), "utf8");
    assert.match(codexBuild, /# generated by: baan --init/);
    assert.match(codexBuild, /model = "gpt-6\.2-sol"/);
    assert.match(codexBuild, /model_reasoning_effort = "medium"/);
    assert.match(codexBuild, /developer_instructions = "/);

    assert.ok(existsSync(path.join(dir, ".agents", "skills", "bug-fix", "SKILL.md")), "ต้องติดตั้ง skill ใน .agents/skills ด้วย");
    assert.ok(existsSync(path.join(dir, ".claude", "skills", "bug-fix", "SKILL.md")), "ต้องติดตั้ง skill ใน .claude/skills ด้วย");
    for (const skillName of ["feature-flow", "req-grill", "wave-plan"]) {
      assert.ok(existsSync(path.join(dir, ".agents", "skills", skillName, "SKILL.md")), `ต้องติดตั้ง skill ${skillName} ใน .agents/skills`);
      assert.ok(existsSync(path.join(dir, ".claude", "skills", skillName, "SKILL.md")), `ต้องติดตั้ง skill ${skillName} ใน .claude/skills`);
    }
    for (const newRole of ["dba", "testplan"]) {
      assert.ok(existsSync(path.join(dir, ".claude", "agents", `${newRole}.md`)), `ต้องสร้าง claude agent ${newRole}`);
      assert.ok(existsSync(path.join(dir, ".agents", "agents", `${newRole}.md`)), `ต้องสร้าง agy agent ${newRole}`);
      assert.ok(existsSync(path.join(dir, ".codex", "agents", `${newRole}.toml`)), `ต้องสร้าง codex agent ${newRole}`);
    }
    assert.ok(logs.some((l) => l.includes("แก้ path")), "ต้องบอกผู้ใช้ให้แก้ config");
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

