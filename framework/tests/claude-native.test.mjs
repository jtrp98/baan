import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { performInit, PROVIDER_SKILLS, CLAUDE_SHARED_SKILLS } from "../src/init.mjs";
import { CLAUDE_HELPER_AGENTS, TEAM_AGENTS } from "../src/role-compiler.mjs";

const TEAM_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// A project skill with one of these names would replace Claude Code's own command in that workspace.
const CLAUDE_BUILTIN_NAMES = ["plan", "code-review", "review", "verify", "simplify", "init", "security-review", "loop", "run"];
const agentsCfg = JSON.parse(readFileSync(path.join(TEAM_DIR, "agents.json"), "utf8"));

test("claude skills: Claude-native skills from skills/claude + shared central skills from root, none shadowing a built-in", () => {
  const nativeDirs = readdirSync(path.join(TEAM_DIR, "skills", "claude"));
  const native = PROVIDER_SKILLS.claude.filter((s) => !CLAUDE_SHARED_SKILLS.includes(s));
  assert.deepEqual([...nativeDirs].sort(), [...native].sort(), "skills/claude must hold exactly the Claude-native skills");
  for (const name of nativeDirs) {
    const text = readFileSync(path.join(TEAM_DIR, "skills", "claude", name, "SKILL.md"), "utf8");
    assert.match(text, new RegExp(`^---\\r?\\nname: ${name}\\r?\\n`), `${name}: frontmatter name must match folder`);
    assert.doesNotMatch(text, /invoke_subagent|run_workflow|generative_ui|ask_question|update_steps/, `${name}: Antigravity-only tool leaked`);
    for (const m of text.matchAll(/shared\/defects/g)) {
      assert.match(text.slice(Math.max(0, m.index - 10), m.index), /<project>\/$/, `${name}: write <project>/shared/defects`);
    }
  }
  for (const s of PROVIDER_SKILLS.claude) assert.ok(!CLAUDE_BUILTIN_NAMES.includes(s), `${s} would shadow a Claude Code built-in`);

  const ws = mkdtempSync(path.join(tmpdir(), "baan-claude-skills-"));
  try {
    for (const old of ["project-survey", "web-design-guidelines"]) {
      mkdirSync(path.join(ws, ".claude", "skills", old), { recursive: true });
      writeFileSync(path.join(ws, ".claude", "skills", old, ".baan-managed"), "old\n", "utf8");
    }
    performInit(ws, TEAM_DIR, () => {});
    for (const s of PROVIDER_SKILLS.claude) {
      const from = CLAUDE_SHARED_SKILLS.includes(s) ? path.join(TEAM_DIR, "skills", s) : path.join(TEAM_DIR, "skills", "claude", s);
      assert.equal(readFileSync(path.join(ws, ".claude", "skills", s, "SKILL.md"), "utf8"), readFileSync(path.join(from, "SKILL.md"), "utf8"), `${s} must come from ${from}`);
    }
    assert.ok(existsSync(path.join(ws, ".claude", "skills", "ui-design-system", "references", "web-rules.md")));
    for (const old of ["project-survey", "web-design-guidelines"]) {
      assert.equal(existsSync(path.join(ws, ".claude", "skills", old)), false, `old managed ${old} must be removed`);
    }
    assert.equal(existsSync(path.join(ws, ".agents", "skills", "feature-flow")), false, "Claude skills must not leak into .agents/skills");
  } finally {
    rmSync(ws, { recursive: true, force: true });
  }
});

test("init: role agents preload installed skills; helper agents take models from agents.json tiers", () => {
  const ws = mkdtempSync(path.join(tmpdir(), "baan-claude-agents-"));
  try {
    performInit(ws, TEAM_DIR, () => {});
    for (const [id, a] of Object.entries(TEAM_AGENTS)) {
      const text = readFileSync(path.join(ws, ".claude", "agents", `${id}.md`), "utf8");
      assert.match(text, /^tools: .*\bAgent\b.*\bSkill\b/m, `${id}: needs Agent (nesting) and Skill`);
      for (const s of a.claudeSkills ?? []) {
        assert.ok(PROVIDER_SKILLS.claude.includes(s), `${id} preloads ${s}, which is not installed`);
        assert.match(text, new RegExp(`^  - ${s}$`, "m"), `${id}: skills frontmatter must list ${s}`);
      }
    }
    for (const [id, h] of Object.entries(CLAUDE_HELPER_AGENTS)) {
      const text = readFileSync(path.join(ws, ".claude", "agents", `${id}.md`), "utf8");
      const tier = agentsCfg.roles[h.source.role].tiers[h.source.tier].claude;
      assert.match(text, new RegExp(`^---\\nname: ${id}\\n`));
      assert.match(text, new RegExp(`^model: ${tier.model}$`, "m"), `${id} model must follow agents.json`);
      assert.match(text, new RegExp(`^effort: ${tier.effort}$`, "m"));
      assert.match(text, /generated by: baan --init/);
    }
    for (const readOnly of ["scout", "auditor"]) {
      assert.match(readFileSync(path.join(ws, ".claude", "agents", `${readOnly}.md`), "utf8"), /^disallowedTools: .*\bEdit\b.*\bWrite\b/m, `${readOnly} is read-only`);
    }
  } finally {
    rmSync(ws, { recursive: true, force: true });
  }
});

test("init: CLAUDE.md is a Claude-native controller and Claude hooks cover prompts, subagents and session end", () => {
  const ws = mkdtempSync(path.join(tmpdir(), "baan-claude-stub-"));
  try {
    performInit(ws, TEAM_DIR, () => {});
    const stub = readFileSync(path.join(ws, "CLAUDE.md"), "utf8");
    assert.match(stub, /Claude Code Native/);
    for (const s of PROVIDER_SKILLS.claude) assert.ok(stub.includes(`\`${s}\``), `CLAUDE.md must name skill ${s}`);
    for (const h of Object.keys(CLAUDE_HELPER_AGENTS)) assert.ok(stub.includes(`\`${h}\``), `CLAUDE.md must name helper ${h}`);
    for (const builtin of ["/plan", "/code-review", "/verify"]) assert.ok(stub.includes(builtin), `CLAUDE.md must route to built-in ${builtin}`);

    const hooks = JSON.parse(readFileSync(path.join(ws, ".claude", "settings.json"), "utf8")).hooks;
    for (const ev of ["SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "SubagentStart", "SubagentStop", "Stop", "SessionEnd"]) {
      assert.ok(hooks[ev]?.some((e) => e.hooks.some((h) => h.command.includes("baan-live-telemetry.mjs --provider=claude"))), `missing claude hook ${ev}`);
    }
    assert.equal(hooks.PreToolUse.find((e) => e.hooks.some((h) => h.command.includes("baan-live-telemetry")))?.matcher, "Agent|Task");
  } finally {
    rmSync(ws, { recursive: true, force: true });
  }
});
