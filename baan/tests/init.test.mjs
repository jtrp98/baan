// Regression: baan --init ติดตั้ง workspace ครั้งเดียว
// (config baan.config.json + ไฟล์นำทาง CLAUDE.md/AGENTS.md)
import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { performInit } from "../src/init.mjs";

const TEAM_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

test("init ครั้งแรก: สร้าง baan.config.json จากตัวอย่าง + CLAUDE.md + AGENTS.md ที่ชี้ไป charter จริง", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-"));
  try {
    const logs = [];
    const res = performInit(dir, TEAM_DIR, (m) => logs.push(m));
    assert.equal(res.config, "written");
    assert.deepEqual(res.stubs.sort(), ["AGENTS.md", "CLAUDE.md"]);
    assert.equal(res.skipped.length, 0);
    // config เป็นไฟล์เดียวที่ราก workspace และมาจาก example ของ package เป๊ะ
    const cfgFile = path.join(dir, "baan.config.json");
    assert.equal(readFileSync(cfgFile, "utf8"), readFileSync(path.join(TEAM_DIR, "baan.example.json"), "utf8"));
    assert.equal(existsSync(path.join(dir, "baan")), false, "ไม่ต้องมีโฟลเดอร์ baan แล้ว");
    // ไฟล์นำทางชี้ไป charter ตัวจริงใน package (ไม่ก๊อปทั้งไฟล์ — ไม่มีสำเนาค้างให้ตกรุ่น)
    for (const name of ["CLAUDE.md", "AGENTS.md"]) {
      const content = readFileSync(path.join(dir, name), "utf8");
      assert.match(content, /generated by: baan --init/);
      assert.ok(content.includes(path.join(TEAM_DIR, "BAAN.md")), `${name} ต้องชี้ path ของ charter`);
      assert.ok(content.includes("baan.config.json"), `${name} ต้องบอกตำแหน่ง config`);
    }
    assert.ok(logs.some((l) => l.includes("แก้ path")), "ต้องบอกผู้ใช้ให้แก้ config");
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("init ซ้ำ: config ที่ผู้ใช้แก้เองไม่ถูกแตะ แต่ไฟล์นำทางที่เราสร้างไว้ถูกอัปเดตใหม่", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-"));
  try {
    performInit(dir, TEAM_DIR, () => {});
    const cfgFile = path.join(dir, "baan.config.json");
    writeFileSync(cfgFile, '{ "main_root": "ของผมเอง" }', "utf8");
    const res = performInit(dir, TEAM_DIR, () => {});
    assert.equal(res.config, "kept");
    assert.equal(readFileSync(cfgFile, "utf8"), '{ "main_root": "ของผมเอง" }');
    assert.deepEqual(res.stubs.sort(), ["AGENTS.md", "CLAUDE.md"], "stub ที่เราสร้างไว้รันซ้ำได้ (regenerate)");
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("init ห้ามทับ CLAUDE.md ของผู้ใช้เอง — ข้ามพร้อมเตือน", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "baan-init-"));
  try {
    writeFileSync(path.join(dir, "CLAUDE.md"), "# กติกาโปรเจกต์ของฉันเอง\n", "utf8");
    const logs = [];
    const res = performInit(dir, TEAM_DIR, (m) => logs.push(m));
    assert.deepEqual(res.skipped, ["CLAUDE.md"]);
    assert.equal(readFileSync(path.join(dir, "CLAUDE.md"), "utf8"), "# กติกาโปรเจกต์ของฉันเอง\n");
    assert.equal(existsSync(path.join(dir, "AGENTS.md")), true, "ตัวอื่นยังสร้างตามปกติ");
    assert.ok(logs.some((l) => l.includes("ข้าม CLAUDE.md")));
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
