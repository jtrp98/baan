// ติดตั้ง baan ลง workspace ครั้งเดียว (baan --init):
// config ของ workspace (baan.config.json) + ไฟล์นำทางให้ AI session สวมบท นายช่าง เองโดยอัตโนมัติ
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROLE_SESSION_RULE } from "./role-guard.mjs";

const STUB_MARKER = "<!-- generated by: baan --init -->";

// CLAUDE.md (Claude Code) และ AGENTS.md (codex และ agent อื่น) ถูกโหลดอัตโนมัติที่รากโปรเจกต์ —
// เราใส่แค่ "ทางเข้า" ที่ชี้ไป charter ตัวจริงใน package ไม่ก๊อปทั้งไฟล์
// เพื่อไม่ให้มีสำเนา charter ค้างใน workspace จนตกรุ่นทุกครั้งที่ update package
// ข้อยกเว้นต้องมาก่อนคำสั่งสวมบท — role ที่ถูกเปิดใน workspace โหลดไฟล์นี้เองอัตโนมัติ (ดู src/role-guard.mjs)
function stubContent(charterPath) {
  return `${STUB_MARKER}
# 🏗️ นายช่าง — ผู้คุมทีม AI 11 role

> **ข้อยกเว้น — อ่านก่อน:** ${ROLE_SESSION_RULE}

ถ้าไม่เข้าข้อยกเว้นด้านบน: คุณคือ นายช่าง ผู้คุมทั้ง 11 ตำแหน่งของทีมพัฒนาซอฟต์แวร์ (ไม่ใช่สมาชิกหนึ่งในทีม)

**ขั้นแรกทันที: อ่าน charter นี้แล้วถือปฏิบัติตลอด session** — \`${charterPath}\`

- เปิด session ราย role ด้วยคำสั่ง \`baan-role\` (ใช้ได้จากทุกที่) · โหมดอัตโนมัติทั้งก้อน: \`baan --target <ชื่อ> --goal "..."\`
- config ของ workspace นี้ (targets/knowledge/memory/defaults): \`./baan.config.json\`
`;
}

export function performInit(targetDir, teamDir, log = console.log) {
  const results = { config: "", stubs: [], skipped: [] };

  const newCfg = path.join(targetDir, "baan.config.json");
  if (existsSync(newCfg)) {
    results.config = "kept";
    log(`มี config อยู่แล้ว (ไม่แตะ): ${newCfg}`);
  } else {
    writeFileSync(newCfg, readFileSync(path.join(teamDir, "baan.example.json"), "utf8"), "utf8");
    results.config = "written";
    log(`สร้าง config จากตัวอย่าง: ${newCfg} — แก้ path ให้ตรงเครื่องนี้ (targets/knowledge/memory) แล้ว git init โฟลเดอร์ memory`);
  }

  const charterPath = path.join(teamDir, "BAAN.md");
  for (const name of ["CLAUDE.md", "AGENTS.md"]) {
    const file = path.join(targetDir, name);
    if (existsSync(file)) {
      const current = readFileSync(file, "utf8");
      if (current.includes(STUB_MARKER)) {
        writeFileSync(file, stubContent(charterPath), "utf8");
        results.stubs.push(name);
        log(`อัปเดต ${name} ใหม่ (เป็นไฟล์ที่ baan --init สร้างไว้)`);
      } else {
        // ไฟล์ของผู้ใช้เอง — ห้ามทับเด็ดขาด ให้รวมเอง
        results.skipped.push(name);
        log(`ข้าม ${name} — มีอยู่แล้วและไม่ได้สร้างโดย baan (เพิ่มบรรทัดชี้ไป ${charterPath} เองถ้าต้องการ)`);
      }
    } else {
      writeFileSync(file, stubContent(charterPath), "utf8");
      results.stubs.push(name);
      log(`สร้าง ${name} — AI session ที่เปิดที่นี่จะสวมบท นายช่าง เองโดยอัตโนมัติ`);
    }
  }
  return results;
}
