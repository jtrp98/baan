import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROLE_SESSION_RULE } from "./role-guard.mjs";

const STUB_MARKER = "<!-- generated by: baan --init -->";

function stubContent(charterPath) {
  return `${STUB_MARKER}
# 🏗️ นายช่าง — BAAN

> **ข้อยกเว้น — อ่านก่อน:** ${ROLE_SESSION_RULE}

ถ้าไม่เข้าข้อยกเว้น: คุณคือ นายช่าง — อ่านและทำตาม ${charterPath}
ใช้ baan run / status / inbox / decide / report
ยืนยัน acceptance กับผู้ใช้ครั้งเดียวก่อน dispatch; ห้ามอนุมัติแทนผู้ใช้
ทีมออกแบบ survey · ui · review และ /pencil ยังใช้ตามเดิม
config: ./baan.config.json
`;
}

const toPosix = (p) => p.split(path.sep).join("/");

function cloneInto(url, dest, log) {
  if (existsSync(dest)) { log(`มี ${dest} อยู่แล้ว (ไม่ clone ทับ)`); return "kept"; }
  const r = spawnSync("git", ["clone", url, dest], { encoding: "utf8", windowsHide: true });
  if (r.status !== 0) throw new Error(`git clone ไม่สำเร็จ: ${(r.error?.message || r.stderr || "unknown Git error").trim().slice(-3000)}`);
  log(`clone ${url} → ${dest}`);
  return "cloned";
}

function generatedConfig(teamDir, targetDir, knowledgeDir, memoryDir, knowledgeName) {
  const example = JSON.parse(readFileSync(path.join(teamDir, "baan.example.json"), "utf8"));
  return {
    knowledge_roots: [{
      name: knowledgeName,
      path: toPosix(knowledgeDir),
      layout: "project",
      ...(memoryDir ? { memory_root: toPosix(memoryDir) } : {}),
      targets: [],
    }],
    defaults: example.defaults,
  };
}

const DESIGN_AGENTS = {
  survey: { tools: "Read, Glob, Grep, Edit, Write, AskUserQuestion", what: "ตรวจว่า requirement ของ module ทำเป็น UI ได้ไหม ชี้ช่องโหว่ ความขัดแย้ง edge case (ชื่อเดิม ruler)" },
  ui: { tools: "Read, Glob, Grep, Edit, Write, Artifact, AskUserQuestion", what: "ออกแบบหน้าจอของ module บน canvas ของ Claude Design โดยดึง component จาก Design System ของ project (ชื่อเดิม crayon)" },
  review: { tools: "Read, Glob, Grep, Edit, Write, Artifact, AskUserQuestion", what: "ตรวจงานออกแบบ (usability · WCAG AA · ใช้ Design System ครบ) ทำ handoff และตรวจหน้าจอที่สร้างแล้วเทียบแบบ (ชื่อเดิม highlighter)" },
};

function agentStub(id, teamDir) {
  const a = DESIGN_AGENTS[id];
  return `---
name: ${id}
description: ${a.what} — ต้องระบุ project และ module
tools: ${a.tools}
---
${STUB_MARKER}

อ่าน role ตัวจริงแล้วทำตามนั้นทั้งหมด: \`${path.join(teamDir, "roles", `${id}.md`)}\`
กติกากลาง: \`${path.join(teamDir, "CONVENTIONS.md")}\` · ตอบเป็นภาษาไทย
`;
}

function pencilStub(teamDir) {
  return `---
description: เค้น requirement ของ module แบบคุยกับผู้ใช้สด (role spec) — ใส่ <project>/<module> เป็น argument
---
${STUB_MARKER}

คุณคือ role \`spec\` โหมดคุยสด สำหรับ: $ARGUMENTS
อ่าน \`${path.join(teamDir, "roles", "spec.md")}\` แล้วทำตาม หัวข้อ "โหมดคุยสด" — ถามผู้ใช้ทีละกลุ่ม แล้วเขียนผลลง \`shared/requirements.md\` ของ module
`;
}

function writeManaged(file, content, results, log) {
  if (existsSync(file) && !readFileSync(file, "utf8").includes(STUB_MARKER)) {
    results.skipped.push(file);
    log(`ข้าม ${file} — มีอยู่แล้วและไม่ได้สร้างโดย baan`);
    return;
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content, "utf8");
  results.design.push(file);
}

const SKILL_MARKER = ".baan-managed";

function installSkills(teamDir, targetDir, results, log) {
  const src = path.join(teamDir, "skills");
  if (!existsSync(src)) return;
  for (const name of readdirSync(src)) {
    const dest = path.join(targetDir, ".claude", "skills", name);
    if (existsSync(dest) && !existsSync(path.join(dest, SKILL_MARKER))) {
      results.skipped.push(dest);
      log(`ข้าม skill ${name} — มีอยู่แล้วและไม่ได้ติดตั้งโดย baan`);
      continue;
    }
    rmSync(dest, { recursive: true, force: true });
    cpSync(path.join(src, name), dest, { recursive: true });
    writeFileSync(path.join(dest, SKILL_MARKER), `ติดตั้งโดย baan --init จาก ${path.join(src, name)} — รัน baan --init ซ้ำเพื่ออัปเดต\n`, "utf8");
    results.design.push(dest);
  }
}

export function performInit(targetDir, teamDir, log = console.log, opts = {}) {
  const results = { config: "", stubs: [], skipped: [], design: [], cloned: [] };
  mkdirSync(targetDir, { recursive: true });

  let knowledgeDir = "";
  let memoryDir = "";
  if (opts.knowledgeGit) {
    knowledgeDir = path.join(targetDir, "knowledge");
    if (cloneInto(opts.knowledgeGit, knowledgeDir, log) === "cloned") results.cloned.push(knowledgeDir);
  }
  if (opts.memoryGit) {
    memoryDir = path.join(targetDir, "memory");
    if (cloneInto(opts.memoryGit, memoryDir, log) === "cloned") results.cloned.push(memoryDir);
  }

  const newCfg = path.join(targetDir, "baan.config.json");
  if (existsSync(newCfg)) {
    results.config = "kept";
    log(`มี config อยู่แล้ว (ไม่แตะ): ${newCfg}`);
  } else if (knowledgeDir) {
    const name = String(opts.knowledgeGit).replace(/[\\/]+$/, "").split(/[\\/:]/).pop().replace(/\.git$/, "") || "knowledge";
    writeFileSync(newCfg, JSON.stringify(generatedConfig(teamDir, targetDir, knowledgeDir, memoryDir, name), null, 2) + "\n", "utf8");
    results.config = "generated";
    log(`สร้าง config ที่ path ตรงเครื่องนี้แล้ว: ${newCfg} — เพิ่ม targets (repo โค้ด) เองเมื่อต้องใช้`);
  } else {
    writeFileSync(newCfg, readFileSync(path.join(teamDir, "baan.example.json"), "utf8"), "utf8");
    results.config = "written";
    log(`สร้าง config จากตัวอย่าง: ${newCfg} — แก้ path ให้ตรงเครื่องนี้ (targets/knowledge/memory) แล้ว git init โฟลเดอร์ memory`);
  }

  for (const id of Object.keys(DESIGN_AGENTS)) writeManaged(path.join(targetDir, ".claude", "agents", `${id}.md`), agentStub(id, teamDir), results, log);
  writeManaged(path.join(targetDir, ".claude", "commands", "pencil.md"), pencilStub(teamDir), results, log);
  installSkills(teamDir, targetDir, results, log);
  if (results.design.length) log(`วางของทีมออกแบบ ${results.design.length} รายการ (agent survey/ui/review · /pencil · skill)`);

  const charterPath = path.join(teamDir, "BAAN.md");
  for (const name of ["CLAUDE.md", "AGENTS.md"]) {
    const file = path.join(targetDir, name);
    if (existsSync(file)) {
      const current = readFileSync(file, "utf8");
      if (current.includes(STUB_MARKER)) {
        writeFileSync(file, stubContent(charterPath), "utf8");
        results.stubs.push(name);
        log(`อัปเดต ${name} ใหม่ (เป็นไฟล์ที่ baan --init สร้างไว้)`);
      } else {
        results.skipped.push(name);
        log(`ข้าม ${name} — มีอยู่แล้วและไม่ได้สร้างโดย baan (เพิ่มบรรทัดชี้ไป ${charterPath} เองถ้าต้องการ)`);
      }
    } else {
      writeFileSync(file, stubContent(charterPath), "utf8");
      results.stubs.push(name);
      log(`สร้าง ${name} — AI session ที่เปิดที่นี่จะสวมบท นายช่าง เองโดยอัตโนมัติ`);
    }
  }
  return results;
}
